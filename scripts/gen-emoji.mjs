// Regenerates the emoji shortcode table from GitHub's gemoji, the `:joy:` names
// Slack and Discord also use: src/lib/emoji-data.ts. Run with `bun scripts/gen-emoji.mjs`.

import { writeFileSync } from 'node:fs';

const url = 'https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json';
const db = await (await fetch(url)).json();
const lines = db.flatMap((e) => e.aliases.map((a) => `${a} ${e.emoji}`));
if (lines.some((l) => /[\n`\\]|\$\{|"""/.test(l))) throw new Error('unexpected character in gemoji data');
const body = lines.join('\n');
const header = 'Generated by scripts/gen-emoji.mjs from github/gemoji. Do not edit.';

writeFileSync(new URL('../src/lib/emoji-data.ts', import.meta.url), `// ${header}\nexport const EMOJI_DATA = \`${body}\`;\n`);
console.log(`${lines.length} shortcodes`);
